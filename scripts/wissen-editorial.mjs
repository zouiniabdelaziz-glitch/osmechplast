// Hooks operate on Markdown tokens, never on the article source file.
export function installEditorial(md) {
  md.core.ruler.push('editorial-structure', (state) => {
    let heading = 0;
    let table = 0;
    for (const token of state.tokens) {
      if (token.type === 'heading_open' && token.tag === 'h2') token.attrSet('id', `${state.env.editorialPrefix || 'abschnitt'}-${++heading}`);
      if (token.type === 'table_open') token.meta = { ...token.meta, tableNumber: ++table };
    }
  });
  md.renderer.rules.table_open = (tokens, index) => `<div class="knowledge-table-scroll" role="region" aria-label="Tabelle ${tokens[index].meta.tableNumber}" tabindex="0"><table>\n`;
  md.renderer.rules.table_close = () => '</table>\n</div>\n';
}

const LAYOUTS = ['full', 'left', 'right'];
const SIZES = ['small', 'medium', 'large'];
export const imageLayout = (value) => LAYOUTS.includes(value) ? value : 'full';
export const imageSize = (value) => SIZES.includes(value) ? value : 'large';
export function validateImageLayout(image) {
  if (image.layout !== undefined && !LAYOUTS.includes(image.layout)) throw new Error('image.layout must be full, left or right');
  if (image.size !== undefined && !SIZES.includes(image.size)) throw new Error('image.size must be small, medium or large');
  if (image.text !== undefined && typeof image.text !== 'string') throw new Error('image.text must be Markdown text');
}

export function tocFromHtml(html = '') {
  // Only anchors generated by our Markdown token hook are eligible.
  return [...String(html).matchAll(/<h2 id="(abschnitt-\d+)">([\s\S]*?)<\/h2>/g)].map((match) => ({
    id: match[1], label: match[2].replace(/<[^>]*>/g, ''),
  })).filter((item) => item.label.trim() !== 'CNC-Drehteile bei ONCC anfragen');
}

